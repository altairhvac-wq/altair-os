import type { Metadata } from "next";

/**
 * The public address of the marketing site.
 *
 * ============ WHY A CONSTANT AND NOT AN ENVIRONMENT VARIABLE ============
 * Link previews (Open Graph, Twitter cards), the canonical URL and robots.txt
 * are read by crawlers that never see a logged-in session, and they are read
 * for the one public origin the videos and captions point at. A preview
 * deployment that resolved its own `VERCEL_URL` here would advertise a
 * `*.vercel.app` address as the canonical home of the product, which is the
 * one thing a canonical must never do. The launch audit (B1) fixed the public
 * name as `altair-op.com`; this is where that decision lives in code.
 */
export const PUBLIC_SITE_ORIGIN = "https://www.altair-op.com";

export const PUBLIC_SITE_NAME = "Altair Operating System";

export const PUBLIC_SITE_TITLE =
  "Altair Operating System · Software for Field Service Businesses";

export const PUBLIC_SITE_DESCRIPTION =
  "Connect leads, customers, jobs, dispatch, technicians, estimates, invoices, payments, and reporting in one field service operating system.";

/** Static 1200×630 card in `public/`, regenerated by `scripts/generate-og-image.mjs`. */
export const PUBLIC_OG_IMAGE_PATH = "/og.png";

export const PUBLIC_OG_IMAGE = {
  url: PUBLIC_OG_IMAGE_PATH,
  width: 1200,
  height: 630,
  alt: "Altair Operating System — software for field service businesses",
} as const;

/**
 * Open Graph + Twitter blocks for a public page.
 *
 * Next.js merges `metadata` objects SHALLOWLY per key, so a page that sets
 * its own `openGraph.title` replaces the layout's whole `openGraph` block —
 * images included. Pages that need their own title or URL spread this helper
 * instead of writing the block by hand, so the image never silently drops.
 *
 * `path` is the page's own path on the public origin. `"./"` resolves to the
 * current route, which is right for every page except the logged-out
 * homepage: that one is rendered at `/` through a middleware rewrite to
 * `/welcome`, so it passes `"/"` explicitly.
 */
export function buildPublicSocialMetadata(input: {
  title?: string;
  description?: string;
  path?: string;
} = {}): Pick<Metadata, "openGraph" | "twitter" | "alternates"> {
  const path = input.path ?? "./";

  return {
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: PUBLIC_SITE_NAME,
      locale: "en_US",
      url: path,
      ...(input.title ? { title: input.title } : {}),
      ...(input.description ? { description: input.description } : {}),
      images: [PUBLIC_OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      ...(input.title ? { title: input.title } : {}),
      ...(input.description ? { description: input.description } : {}),
      images: [PUBLIC_OG_IMAGE_PATH],
    },
  };
}
